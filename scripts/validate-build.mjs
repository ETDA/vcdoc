#!/usr/bin/env node
/**
 * Static validation of the Docusaurus build output (build/).
 *
 * Run AFTER `npm run build`. Verifies:
 *   1. Every source doc (working draft and every frozen snapshot) produced a page.
 *   2. Locale layout is correct: Thai at the root + /thai-vc-arf/..., English at /en/... .
 *   3. No raw HTML comments leaked into the source (format-conversion regression check).
 *   4. Mermaid diagrams: every top-level mermaid block parses without syntax errors
 *      (using the mermaid parser under jsdom; client-side rendering is covered by E2E).
 *   5. Image integrity: every referenced image exists on disk and no image file is
 *      orphaned (referenced-but-missing or present-but-unused images are both errors).
 *   6. Version chain: versions.json and versions.meta.mjs agree, every frozen page
 *      carries its Thai release date, and the history/delta routes were built.
 *   7. Frozen trees still hash to the value recorded in versions.meta.mjs.
 *   8. Every chapter carries an explicit sidebar_position, so the autogenerated
 *      sidebar cannot drop dotted chapters (06.5, 08.3, 12.1) to the end.
 *   9. AI access artifacts: llms.txt, a Markdown twin per current doc, faq.json,
 *      and the FAQPage JSON-LD.
 *
 * Exits non-zero on the first failure.
 */
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join, dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';
import { chain, pairs, formatThaiDate } from '../versions.meta.mjs';
import { assertTreeHash } from '../versions.hash.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BUILD = join(ROOT, 'build');
const DOCS = join(ROOT, 'docs');

const failures = [];
const checks = [];
const ok = (msg) => checks.push(`  PASS  ${msg}`);
const fail = (msg) => {
  failures.push(msg);
  checks.push(`  FAIL  ${msg}`);
};

// --- helpers ---------------------------------------------------------------

// Docusaurus default slug: filename without .md, with a leading integer prefix
// ("00-", "01-", ... "16-") stripped. Dot-numbered files ("06.5-", "08.1-",
// "12.1-") keep their prefix. Verified against build/sitemap.xml.
const slugFromFilename = (filename) => filename.replace(/\.md$/, '').replace(/^\d+-/, '');

function mdFiles(dir) {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .sort();
}

const snapshots = chain.filter((entry) => entry.kind === 'snapshot');
const working = chain.find((entry) => entry.kind === 'working');

/** Source doc tree + the URL prefix its pages are built under. */
const trees = [
  { dir: 'docs', prefix: '', label: 'current' },
  ...snapshots.map((entry) => ({
    dir: entry.docTree,
    prefix: entry.id,
    label: entry.id,
    entry,
  })),
];

const buildPath = (prefix, ...parts) =>
  join(BUILD, ...(prefix ? [prefix] : []), ...parts);

// --- 1. all docs generated -------------------------------------------------

console.log('1. all docs generated');
if (!existsSync(BUILD)) {
  fail(`build/ directory not found — run "npm run build" first`);
} else {
  for (const tree of trees) {
    const thaiDir = join(ROOT, tree.dir, 'thai-vc-arf');
    const enDir = join(ROOT, tree.dir, 'en', 'thai-vc-arf');
    if (!existsSync(thaiDir)) {
      fail(`missing doc tree ${tree.dir}/thai-vc-arf`);
      continue;
    }

    for (const f of mdFiles(thaiDir).filter((name) => name !== 'README.md')) {
      const slug = slugFromFilename(f);
      const html = buildPath(tree.prefix, 'thai-vc-arf', slug, 'index.html');
      if (existsSync(html)) ok(`${tree.dir}/thai-vc-arf/${f} -> /${tree.prefix ? `${tree.prefix}/` : ''}thai-vc-arf/${slug}/`);
      else fail(`missing page for ${tree.dir}/thai-vc-arf/${f} (expected ${html})`);
    }

    // README.md becomes the Thai category landing page
    if (existsSync(buildPath(tree.prefix, 'thai-vc-arf', 'index.html'))) {
      ok(`${tree.dir}/thai-vc-arf/README.md -> /${tree.prefix ? `${tree.prefix}/` : ''}thai-vc-arf/`);
    } else {
      fail(`missing Thai category landing page for ${tree.dir} (from README.md)`);
    }

    if (!existsSync(enDir)) continue;
    for (const f of mdFiles(enDir)) {
      const slug = slugFromFilename(f);
      const html = buildPath(tree.prefix, 'en', 'thai-vc-arf', slug, 'index.html');
      if (existsSync(html)) ok(`${tree.dir}/en/thai-vc-arf/${f} -> /${tree.prefix ? `${tree.prefix}/` : ''}en/thai-vc-arf/${slug}/`);
      else fail(`missing page for ${tree.dir}/en/thai-vc-arf/${f}`);
    }
  }
}

// --- 2. locale support -----------------------------------------------------

console.log('2. locale support');
if (existsSync(BUILD)) {
  const readHtml = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : '');

  const home = readHtml(join(BUILD, 'index.html'));
  if (home.includes('Thai VC ARF')) ok('homepage / serves the Thai index');
  else fail('homepage / does not contain the Thai index title');

  const en = readHtml(join(BUILD, 'en', 'thai-vc-arf', 'minimal-interoperability-reference', 'index.html'));
  if (en.includes("Thailand's VC stack")) ok('English summary served at /en/thai-vc-arf/...');
  else fail('English summary page missing or does not contain its title');

  const thaiPage = readHtml(join(BUILD, 'thai-vc-arf', 'scope', 'index.html'));
  if (thaiPage.includes('ขอบข่าย')) ok('Thai chapter content present (scope page)');
  else fail('Thai chapter page missing expected content');

  for (const tree of trees.filter((item) => item.entry)) {
    const page = readHtml(buildPath(tree.prefix, 'thai-vc-arf', 'scope', 'index.html'));
    if (page.includes('ขอบข่าย')) ok(`frozen ${tree.label}: scope chapter renders under /${tree.prefix}/thai-vc-arf/`);
    else fail(`frozen ${tree.label}: scope chapter missing under /${tree.prefix}/thai-vc-arf/`);
  }
}

// --- 3. no raw HTML comments (format regression) ---------------------------

console.log('3. format conversion (no raw HTML comments)');
{
  let leaked = 0;
  // A raw "<!--" is only a problem at TOP LEVEL (depth 0). Nested "<!-- ... -->"
  // inside an already-converted {/* ... */} comment is literal text and is fine.
  const topLevelHtmlLines = (text) => {
    const hits = [];
    let depth = 0;
    let i = 0;
    let line = 1;
    while (i < text.length) {
      const ch = text[i];
      if (text.startsWith('{/*', i)) {
        depth += 1;
        i += 3;
      } else if (text.startsWith('*/}', i)) {
        depth = Math.max(0, depth - 1);
        i += 3;
      } else if (text.startsWith('<!--', i) && depth === 0) {
        hits.push(line);
        i += 4;
      } else {
        if (ch === '\n') line += 1;
        i += 1;
      }
    }
    return hits;
  };
  const scan = (dir) => {
    if (!existsSync(dir)) return;
    for (const f of readdirSync(dir)) {
      if (!f.endsWith('.md')) continue;
      const p = join(dir, f);
      const text = readFileSync(p, 'utf8');
      for (const ln of topLevelHtmlLines(text)) {
        leaked += 1;
        fail(`top-level HTML comment in ${p}:${ln}`);
      }
    }
  };
  for (const tree of trees) {
    scan(join(ROOT, tree.dir, 'thai-vc-arf'));
    scan(join(ROOT, tree.dir, 'en', 'thai-vc-arf'));
  }
  if (leaked === 0) ok('no top-level HTML comments in source markdown');
}

// --- 4. mermaid syntax (every top-level block parses) ---------------------

console.log('4. mermaid syntax');
{
  // mermaid's flowchart parser calls DOMPurify.addHook, which needs a DOM.
  // Provide a minimal jsdom window BEFORE dynamically importing mermaid so the
  // flowchart diagram module (lazily loaded on first parse) sees it.
  const dom = new JSDOM('<!DOCTYPE html><html><body></body></html>');
  globalThis.window = dom.window;
  globalThis.document = dom.window.document;
  Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
  const { default: mermaid } = await import('mermaid');
  mermaid.initialize({ startOnLoad: false });

  // collect top-level ```mermaid blocks (skip those inside {/* */} comments,
  // which are hidden agent metadata, not rendered diagrams)
  const blocks = [];
  const scan = (dir) => {
    if (!existsSync(dir)) return;
    for (const f of readdirSync(dir)) {
      if (!f.endsWith('.md')) continue;
      const p = join(dir, f);
      const lines = readFileSync(p, 'utf8').split('\n');
      let depth = 0;
      for (let idx = 0; idx < lines.length; idx++) {
        const line = lines[idx];
        if (line.trim().startsWith('```mermaid') && depth === 0) {
          const codeLines = [];
          let j = idx + 1;
          while (j < lines.length && !lines[j].trim().startsWith('```')) {
            codeLines.push(lines[j]);
            j += 1;
          }
          blocks.push({ code: codeLines.join('\n'), file: relative(ROOT, p), line: idx + 1 });
          idx = j; // skip to the closing fence
          continue;
        }
        const opens = (line.match(/\{\/\*/g) || []).length;
        const closes = (line.match(/\*\/\}/g) || []).length;
        depth = Math.max(0, depth + opens - closes);
      }
    }
  };
  for (const tree of trees) {
    scan(join(ROOT, tree.dir, 'thai-vc-arf'));
    scan(join(ROOT, tree.dir, 'en', 'thai-vc-arf'));
  }

  if (blocks.length === 0) {
    fail('no mermaid blocks found in source');
  } else {
    let parsed = 0;
    for (const b of blocks) {
      try {
        await mermaid.parse(b.code);
        parsed += 1;
      } catch (e) {
        fail(`mermaid syntax error in ${b.file}:${b.line}: ${e.message.split('\n')[0]}`);
      }
    }
    if (parsed === blocks.length) ok(`${parsed} mermaid diagram(s) all parse cleanly`);
  }
}

// --- 5. image integrity ----------------------------------------------------

console.log('5. image integrity');
{
  const walk = (dir) => {
    const out = [];
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, e.name);
      if (e.isDirectory()) out.push(...walk(p));
      else out.push(p);
    }
    return out;
  };
  const isImage = (p) => /\.(png|jpe?g|gif|svg|webp)$/i.test(p);

  // Per tree, so a snapshot's orphan check is not masked by the working draft.
  for (const tree of trees) {
    const treeDir = join(ROOT, tree.dir);
    if (!existsSync(treeDir)) continue;
    const allFiles = walk(treeDir);
    const imgFiles = allFiles.filter(isImage);

    const refs = [];
    const refRe = /!\[[^\]]*\]\(([^)]+)\)/g;
    for (const md of allFiles.filter((p) => p.endsWith('.md'))) {
      const text = readFileSync(md, 'utf8');
      let m;
      while ((m = refRe.exec(text)) !== null) {
        if (isImage(m[1])) refs.push({ target: m[1], md });
      }
    }

    let broken = 0;
    const referenced = new Set();
    for (const { target, md } of refs) {
      const abs = resolve(dirname(md), target);
      if (!existsSync(abs)) {
        broken += 1;
        fail(`referenced image missing: ${target} (in ${relative(ROOT, md)})`);
      } else {
        referenced.add(abs);
      }
    }
    if (broken === 0) ok(`${tree.dir}: ${refs.length} image reference(s) all resolve`);

    const orphans = imgFiles.filter((p) => !referenced.has(p));
    if (orphans.length === 0) ok(`${tree.dir}: ${imgFiles.length} image file(s) all referenced`);
    else for (const o of orphans) fail(`orphan image (never referenced): ${relative(ROOT, o)}`);
  }
}

// --- 6. version chain metadata and routes ---------------------------------

console.log('6. version chain metadata and routes');
{
  const versionsPath = join(ROOT, 'versions.json');
  const versionsJson = existsSync(versionsPath) ? JSON.parse(readFileSync(versionsPath, 'utf8')) : [];

  if (versionsJson.length === 0) fail('versions.json is empty — no frozen version was cut');

  for (const id of versionsJson) {
    const entry = snapshots.find((snapshot) => snapshot.id === id);
    if (!entry) {
      fail(`versions.json lists ${id} with no versions.meta.mjs record`);
      continue;
    }
    if (!/^\d{4}-\d{2}-\d{2}$/.test(entry.released)) {
      fail(`${id}: released "${entry.released}" is not YYYY-MM-DD`);
    } else {
      ok(`${id}: released ${entry.released} (${formatThaiDate(entry.released)})`);
    }
    if (!formatThaiDate(entry.released)) fail(`${id}: empty Thai release date`);
    if (!existsSync(join(ROOT, entry.docTree))) fail(`${id}: missing doc tree ${entry.docTree}`);
  }

  for (const entry of snapshots) {
    if (!versionsJson.includes(entry.id)) fail(`${entry.id} has a meta record but is not in versions.json`);
  }

  // Each frozen page must show its own Thai release date.
  for (const entry of snapshots) {
    const thaiDate = formatThaiDate(entry.released);
    const page = join(BUILD, entry.id, 'thai-vc-arf', 'scope', 'index.html');
    if (!existsSync(page)) {
      fail(`${entry.id}: missing frozen page ${relative(ROOT, page)}`);
      continue;
    }
    const html = readFileSync(page, 'utf8');
    if (html.includes(thaiDate)) ok(`${entry.id}: release date "${thaiDate}" present on the page`);
    else fail(`${entry.id}: release date "${thaiDate}" missing from the page`);
    if (html.includes('เผยแพร่') && html.includes('เก็บถาวรแล้ว')) {
      ok(`${entry.id}: frozen notice rendered`);
    } else {
      fail(`${entry.id}: Thai frozen notice (เก็บถาวรแล้ว / เผยแพร่) missing`);
    }
  }

  if (working) {
    const current = join(BUILD, 'thai-vc-arf', 'scope', 'index.html');
    const html = existsSync(current) ? readFileSync(current, 'utf8') : '';
    if (html.includes('กำลังจัดทำ')) ok('current draft shows "กำลังจัดทำ"');
    else fail('current draft does not show "กำลังจัดทำ"');
  }

  if (existsSync(join(BUILD, 'versions', 'index.html'))) ok('build/versions/index.html exists');
  else fail('missing build/versions/index.html');

  for (const { from, to } of pairs()) {
    const hub = join(BUILD, 'versions', 'diff', `${from.id}__${to.id}`, 'index.html');
    const clauses = join(BUILD, 'versions', 'diff', `${from.id}__${to.id}`, 'clauses', 'index.html');
    if (existsSync(hub)) ok(`delta hub ${from.id}__${to.id} exists`);
    else fail(`missing delta hub ${relative(ROOT, hub)}`);
    if (existsSync(clauses)) ok(`clause table ${from.id}__${to.id} exists`);
    else fail(`missing clause table ${relative(ROOT, clauses)}`);

    const hubHtml = existsSync(hub) ? readFileSync(hub, 'utf8') : '';
    if (hubHtml.includes(`/versions/diff/${from.id}__${to.id}/`)) {
      ok(`delta hub ${from.id}__${to.id} links to chapter diffs`);
    } else {
      fail(`delta hub ${from.id}__${to.id} has no chapter links`);
    }
  }
}

// --- 7. frozen trees unchanged --------------------------------------------

console.log('7. frozen tree integrity');
for (const entry of snapshots) {
  try {
    assertTreeHash(entry);
    ok(`${entry.id}: tree hash matches ${entry.treeHash.slice(0, 12)}…`);
  } catch (error) {
    fail(error.message);
  }
}

// --- 8. sidebar ordering ---------------------------------------------------

console.log('8. sidebar ordering');
const chapterTrees = ['docs/thai-vc-arf', ...snapshots.map((entry) => `${entry.docTree}/thai-vc-arf`)];
const unordered = [];
for (const tree of chapterTrees) {
  const walk = (dir) => {
    for (const entry of readdirSync(join(ROOT, dir), { withFileTypes: true })) {
      const path = `${dir}/${entry.name}`;
      if (entry.isDirectory()) walk(path);
      else if (entry.name.endsWith('.md')) {
        const head = readFileSync(join(ROOT, path), 'utf8').slice(0, 400);
        if (!/^sidebar_position:/m.test(head)) unordered.push(path);
      }
    }
  };
  walk(tree);
}
if (unordered.length === 0) ok(`every chapter has sidebar_position (${chapterTrees.length} tree(s))`);
else fail(`missing sidebar_position in ${unordered.length} file(s): ${unordered.slice(0, 4).join(', ')}`);

// --- 9. AI access artifacts -------------------------------------------------

console.log('9. AI access artifacts');
{
  const walk = (dir) => {
    if (!existsSync(dir)) return [];
    const out = [];
    for (const entry of readdirSync(dir, {withFileTypes: true})) {
      const p = join(dir, entry.name);
      if (entry.isDirectory()) out.push(...walk(p));
      else out.push(p);
    }
    return out;
  };

  const llmsPath = join(BUILD, 'llms.txt');
  if (!existsSync(llmsPath)) {
    fail('missing build/llms.txt');
  } else {
    const llms = readFileSync(llmsPath, 'utf8');
    const problems = [];
    if (!llms.startsWith('# Thai VC ARF')) problems.push('does not start with "# Thai VC ARF"');
    for (const heading of ['## Overview', '## Chapters', '## FAQ', '## English', '## Versions']) {
      if (!llms.includes(heading)) problems.push(`missing ${heading}`);
    }
    if (problems.length > 0) fail(`build/llms.txt ${problems.join(', ')}`);
    else ok('build/llms.txt has the expected header and sections');

    const sitePrefix = '/vcdoc/';
    let checked = 0;
    let broken = 0;
    for (const match of llms.matchAll(/\[[^\]]*\]\(([^)\s]+)\)/g)) {
      const href = match[1];
      if (!href.startsWith('https://') && !href.startsWith('/')) continue;
      let pathname;
      try {
        pathname = new URL(href, 'https://ETDA.github.io').pathname;
      } catch {
        fail(`build/llms.txt has an unparsable link ${href}`);
        continue;
      }
      if (!pathname.startsWith(sitePrefix)) continue;
      const rel = decodeURIComponent(pathname.slice(sitePrefix.length));
      const target = rel.endsWith('/')
        ? join(BUILD, rel, 'index.html')
        : /\.(md|json)$/.test(rel)
          ? join(BUILD, rel)
          : join(BUILD, rel, 'index.html');
      checked += 1;
      if (!existsSync(target)) {
        broken += 1;
        fail(`llms.txt link ${href} has no build output (${relative(ROOT, target)})`);
      }
    }
    if (checked === 0) fail('build/llms.txt has no internal links');
    else if (broken === 0) ok(`build/llms.txt: ${checked} internal link(s) all resolve`);
  }

  const faqPath = join(BUILD, 'faq.json');
  let faq = null;
  if (!existsSync(faqPath)) {
    fail('missing build/faq.json');
  } else {
    try {
      faq = JSON.parse(readFileSync(faqPath, 'utf8'));
    } catch (error) {
      fail(`build/faq.json does not parse: ${error.message}`);
    }
  }
  if (faq) {
    const problems = [];
    if (!Array.isArray(faq.items)) problems.push('items is not an array');
    else {
      if (faq.count !== faq.items.length) problems.push(`count ${faq.count} !== items ${faq.items.length}`);
      if (faq.items.length < 30) problems.push(`only ${faq.items.length} items (expected >= 30)`);
      for (const item of faq.items) {
        for (const key of ['id', 'question', 'answer', 'section', 'sectionUrls', 'status', 'statusLabel', 'url']) {
          if (!(key in item)) problems.push(`${item.id ?? '?'} missing ${key}`);
        }
        if (item.status !== 'answered' && item.status !== 'pending') problems.push(`${item.id} has status ${item.status}`);
        if (!Array.isArray(item.sectionUrls)) problems.push(`${item.id} sectionUrls is not an array`);
        if (!item.question || !item.answer) problems.push(`${item.id} has an empty question or answer`);
      }
    }
    if (problems.length > 0) fail(`build/faq.json: ${problems.slice(0, 4).join('; ')}`);
    else ok(`build/faq.json: ${faq.items.length} FAQ rows, all fields valid`);
  }

  const twins = walk(BUILD).filter((p) => p.endsWith('.md'));
  const badTwins = [];
  for (const twin of twins) {
    const text = readFileSync(twin, 'utf8');
    if (text.startsWith('---')) badTwins.push(`${relative(ROOT, twin)} starts with front matter`);
    if (text.includes('{/*')) badTwins.push(`${relative(ROOT, twin)} still has an MDX comment`);
    if (!text.startsWith('> Canonical: https://')) badTwins.push(`${relative(ROOT, twin)} has no canonical line`);
  }
  if (badTwins.length > 0) fail(badTwins.slice(0, 4).join('; '));

  const sourceTwins =
    mdFiles(join(ROOT, 'docs', 'thai-vc-arf')).length +
    (existsSync(join(ROOT, 'docs', 'en', 'thai-vc-arf'))
      ? mdFiles(join(ROOT, 'docs', 'en', 'thai-vc-arf')).length
      : 0);
  if (twins.length !== sourceTwins) {
    fail(`found ${twins.length} Markdown twin(s), expected ${sourceTwins} for the current docs`);
  } else {
    ok(`${twins.length} Markdown twins match the current docs`);
  }

  if (faq) {
    const faqHtmlPath = join(BUILD, 'thai-vc-arf', 'faq', 'index.html');
    const html = existsSync(faqHtmlPath) ? readFileSync(faqHtmlPath, 'utf8') : '';
    if (!html.includes('"@type":"FAQPage"')) {
      fail('build/thai-vc-arf/faq/index.html has no FAQPage JSON-LD');
    } else {
      const blocks = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].map((m) => m[1]);
      const block = blocks.find((text) => text.includes('"@type":"FAQPage"'));
      try {
        const data = JSON.parse(block);
        const count = Array.isArray(data.mainEntity) ? data.mainEntity.length : -1;
        if (count === faq.items.length) ok(`FAQPage JSON-LD: ${count} questions match faq.json`);
        else fail(`FAQPage JSON-LD has ${count} questions, faq.json has ${faq.items.length}`);
        const withMarkdown = (data.mainEntity ?? []).filter(
          (item) =>
            /\]\(|`|\*\*/.test(item.name ?? '') ||
            /\]\(|`|\*\*/.test(item.acceptedAnswer?.text ?? ''),
        );
        if (withMarkdown.length > 0) {
          fail(`FAQPage JSON-LD has Markdown left in ${withMarkdown.length} question(s)`);
        } else {
          ok('FAQPage JSON-LD answers are plain text');
        }
      } catch (error) {
        fail(`FAQPage JSON-LD does not parse: ${error.message}`);
      }
    }
  }

  const scopePath = join(BUILD, 'thai-vc-arf', 'scope', 'index.html');
  const scopeHtml = existsSync(scopePath) ? readFileSync(scopePath, 'utf8') : '';
  if (/rel="alternate" type="text\/markdown"/.test(scopeHtml)) ok('doc pages advertise their Markdown twin');
  else fail('build/thai-vc-arf/scope/index.html has no rel="alternate" type="text/markdown"');

  const homeHtml = existsSync(join(BUILD, 'index.html')) ? readFileSync(join(BUILD, 'index.html'), 'utf8') : '';
  // The minifier drops attribute quotes, so match the value, not the literal tag.
  if (/rel=["']?describedby["']?/.test(homeHtml) && homeHtml.includes('llms.txt')) {
    ok('homepage links llms.txt via rel="describedby"');
  } else {
    fail('build/index.html does not advertise llms.txt via rel="describedby"');
  }
}

// --- summary ---------------------------------------------------------------

console.log('\n' + checks.join('\n'));
if (failures.length > 0) {
  console.error(`\n${failures.length} validation failure(s).`);
  process.exit(1);
}
console.log('\nStatic build validation passed.');
